#!/usr/bin/env python3
"""Subset Material Symbols Rounded by PUA codepoints + emit TS icon map."""
import pathlib, subprocess, sys

TMP = pathlib.Path("/tmp/msr")
OUT = pathlib.Path("/home/z/my-project/public/fonts/material-symbols.woff2")
TSMAP = pathlib.Path("/home/z/my-project/src/data/icon-codepoints.ts")

ICONS = """
menu search close arrow_back arrow_upward keyboard_arrow_up keyboard_arrow_down
chevron_left chevron_right expand_more more_vert check done done_all
add settings help info photo_library explore group construction photo_album
favorite delete archive restore_from_trash delete_forever share edit tune crop
download print cast zoom_in zoom_out rotate_right auto_awesome auto_fix
star star_rate bookmark place schedule person account_circle photo_camera
image movie pets restaurant local_cafe beach_access forest light_mode dark_mode
cloud_upload photo photo_camera collections_bookmark select_all folder_open fullscreen refresh
photo_filter wb_sunny apps account_box send arrow_forward tag map
brightness_auto play_arrow pause keyboard slideshow contrast speed
""".split()

from fontTools.ttLib import TTFont
f = TTFont(TMP / "msr-full.woff2")
pua = {name: cp for cp, name in f.getBestCmap().items() if 0xE000 <= cp <= 0xF8FF}

missing = [i for i in ICONS if i not in pua]
if missing:
    sys.exit(f"MISSING ICONS: {missing}")
print(f"all {len(ICONS)} icons found in PUA cmap")

uni = ",".join(hex(pua[i]) for i in ICONS)
subprocess.run([
    "pyftsubset", str(TMP / "msr-full.woff2"),
    f"--unicodes={uni}",
    "--layout-features=",
    "--flavor=woff2",
    f"--output-file={OUT}",
    "--no-hinting",
], check=True)
print(f"subset written: {OUT} ({OUT.stat().st_size//1024} KB)")

# verify subset kept the codepoints
s = TTFont(OUT)
cmap = s.getBestCmap()
kept = [i for i in ICONS if pua[i] in cmap]
print(f"verified: {len(kept)}/{len(ICONS)} icons kept in subset")
assert len(kept) == len(ICONS)

lines = ["// AUTO-GENERATED by scripts/subset-icons.py — Material Symbols Rounded codepoints",
         "export const ICONS = {"]
for i in ICONS:
    lines.append(f'  {i}: 0x{pua[i]:X},')
lines.append("} as const;")
lines.append("export type IconName = keyof typeof ICONS;")
TSMAP.parent.mkdir(parents=True, exist_ok=True)
TSMAP.write_text("\n".join(lines) + "\n")
print(f"wrote {TSMAP}")
